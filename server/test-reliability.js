require('./config');
const assert=require('node:assert/strict');
const db=require('./db');
const {sign}=require('./security');
async function main(){
  if(!/\/velathier_test_\d+_\d+\?replicaSet=velaTest$/.test(process.env.MONGO_URI||''))throw Error('Use test-replica.js');
  await db.connect();assert(db.status().transactions);
  const buyer=await db.models.users.findOne({id:'u_demo'}).lean(),admin=await db.models.users.findOne({id:'u_admin'}).lean();
  const call=async(base,url,body,user=buyer)=>{const r=await fetch(base+url,{method:'POST',headers:{'Content-Type':'application/json',Authorization:`Bearer ${sign(user)}`},body:JSON.stringify(body)});return {status:r.status,body:await r.json()};};
  const base=process.env.TEST_BASE_URL;
  const created=await call(base,'/api/products',{title:'Replica race last stock',cat:'tops',price:100000,variants:[{color:'Trắng',size:'M',stock:1}]},admin);assert.equal(created.status,201,JSON.stringify(created.body));
  const p=created.body,body={items:[{productId:p.id,variantId:p.variants[0].id,qty:1}],payMethod:'cod',address:{fullName:'Replica Test',phone:'0901234567',provinceCode: '01', wardCode: '00004',line1:'1 Test'}};
  const result=await Promise.all([base,process.env.TEST_SECOND_BASE_URL].map(b=>call(b,'/api/orders',{...body,requestKey:crypto.randomUUID()})));
  assert.equal(result.filter(r=>r.status===201).length,1,JSON.stringify(result));assert(result.some(r=>[400,409].includes(r.status)));
  assert.equal((await db.models.products.findOne({id:p.id}).lean()).variants[0].stock,0);
  console.log('PASS multi-process last-stock checkout: exactly one success, stock zero');
  const order=result.find(r=>r.status===201).body;
  const before=await db.models.orders.findOne({id:order.id}).lean();
  require('./mongo-store').injectFailureForTest();
  await assert.rejects(db.run(()=>{db.orders.byId(order.id).refundTransactions=[{reference:'FAULT-TEST',amount:1000}];db.products.byId(p.id).variants[0].stock=99;db.vouchers.all()[0].usedCount++;}),/Injected/);
  assert.equal((await db.models.products.findOne({id:p.id}).lean()).variants[0].stock,0);
  assert.deepEqual((await db.models.orders.findOne({id:order.id}).lean()).refundTransactions,before.refundTransactions);
  console.log('PASS injected mid-commit failure: stock/refund ledger rolled back');
  const worker=require('./outbox-worker');
  await db.run(()=>db.load().mailOutbox.push({id:'outbox-test',eventKey:'test-event',status:'pending',attempts:0,nextAttemptAt:0,emailId:'missing',payload:worker.seal({to:'test@example.invalid',html:'test'})}));
  let release;const slow=new Promise(r=>{release=r;});let started;const began=new Promise(r=>{started=r;});
  const sending=worker.tick(async()=>{started();await slow;});await began;
  assert.equal(await worker.tick(async()=>{throw Error('duplicate claim');}),false);
  const response=await Promise.race([fetch(base+'/api/auth/me',{headers:{Authorization:`Bearer ${sign(buyer)}`}}),new Promise((_,reject)=>setTimeout(()=>reject(Error('API blocked by SMTP')),2000))]);assert(response.ok);release();await sending;
  assert.equal((await db.models.mailOutbox.findOne({id:'outbox-test'}).lean()).status,'sent');
  console.log('PASS slow SMTP does not block API; atomic claim excludes second worker');
  const count=await db.models.mailOutbox.countDocuments();
  require('./mongo-store').injectFailureForTest();
  await assert.rejects(db.run(()=>{db.load().mailOutbox.push({id:'phantom',eventKey:'phantom',status:'pending',attempts:0,nextAttemptAt:0});db.products.byId(p.id).title='FAULT';}),/Injected/);
  assert.equal(await db.models.mailOutbox.countDocuments(),count);
  console.log('PASS failed transaction produces no phantom confirmation');
  await db.models.mailOutbox.create({id:'retry-test',eventKey:'retry-test',status:'pending',attempts:4,nextAttemptAt:0,payload:worker.seal({html:'test'})});
  await worker.tick(async()=>{throw Error('Injected SMTP failure');});
  assert.equal((await db.models.mailOutbox.findOne({id:'retry-test'}).lean()).status,'dead');
  assert.equal(await worker.tick(async()=>{throw Error('must not retry dead letter');}),false);
  console.log('PASS failed SMTP reaches dead letter after bounded retries');
  console.log('Reliability: 5 scenarios passed, 0 failed');
}
main().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>db.close());
